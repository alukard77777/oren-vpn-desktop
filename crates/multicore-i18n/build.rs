//! Turns the English gettext catalog into a sorted Rust lookup table.
//!
//! The catalog is the one Slint bundles for `@tr()` (`apps/multicore-desktop/translations`),
//! so the UI strings and the strings built in Rust share one source of truth. The source
//! language is Russian: a `msgid` is the exact Russian text, `msgstr` its English text.

use std::collections::BTreeMap;
use std::fmt::Write as _;
use std::path::PathBuf;

const CATALOG: &str =
    "../../apps/multicore-desktop/translations/en/LC_MESSAGES/multicore-desktop.po";

fn main() {
    let manifest_dir = PathBuf::from(
        std::env::var_os("CARGO_MANIFEST_DIR").expect("Cargo must set CARGO_MANIFEST_DIR"),
    );
    let path = manifest_dir.join(CATALOG);
    println!("cargo:rerun-if-changed={}", path.display());
    let catalog = rspolib::pofile(path.to_str().expect("catalog path is UTF-8"))
        .unwrap_or_else(|error| panic!("cannot parse {}: {error}", path.display()));

    let plural_forms = catalog
        .metadata
        .get("Plural-Forms")
        .map(String::as_str)
        .unwrap_or_default()
        .replace(' ', "");
    assert!(
        plural_forms.contains("nplurals=2;plural=(n!=1);")
            || plural_forms.contains("nplurals=2;plural=n!=1;"),
        "the English catalog must use the English plural rule (n != 1), got {plural_forms:?}"
    );

    let mut singular = BTreeMap::new();
    let mut plural = BTreeMap::new();
    for entry in &catalog.entries {
        if entry.obsolete {
            continue;
        }
        assert!(
            entry.msgctxt.is_none(),
            "catalog entries carry no context (Slint compiles with DefaultTranslationContext::None): {:?}",
            entry.msgid
        );
        assert!(
            !entry.flags.iter().any(|flag| flag == "fuzzy"),
            "fuzzy entry left in the catalog: {:?}",
            entry.msgid
        );
        if let Some(msgid_plural) = &entry.msgid_plural {
            assert!(
                entry.msgstr_plural.len() == 2 && entry.msgstr_plural.iter().all(|s| !s.is_empty()),
                "plural entry needs msgstr[0] and msgstr[1]: {:?}",
                entry.msgid
            );
            let previous = plural.insert(
                (entry.msgid.clone(), msgid_plural.clone()),
                (
                    entry.msgstr_plural[0].clone(),
                    entry.msgstr_plural[1].clone(),
                ),
            );
            assert!(
                previous.is_none(),
                "duplicate plural msgid: {:?}",
                entry.msgid
            );
        } else {
            let msgstr = entry.msgstr.clone().unwrap_or_default();
            assert!(
                !msgstr.is_empty(),
                "untranslated catalog entry: {:?}",
                entry.msgid
            );
            let previous = singular.insert(entry.msgid.clone(), msgstr);
            assert!(previous.is_none(), "duplicate msgid: {:?}", entry.msgid);
        }
    }

    let mut out = String::new();
    out.push_str("// Generated by build.rs from the English gettext catalog. Do not edit.\n");
    let _ = writeln!(out, "pub(crate) static SINGULAR: &[(&str, &str)] = &[");
    for (msgid, msgstr) in &singular {
        let _ = writeln!(out, "    ({msgid:?}, {msgstr:?}),");
    }
    out.push_str("];\n");
    let _ = writeln!(out, "pub(crate) static PLURAL: &[PluralEntry] = &[");
    for ((msgid, msgid_plural), (one, other)) in &plural {
        let _ = writeln!(
            out,
            "    (({msgid:?}, {msgid_plural:?}), ({one:?}, {other:?})),"
        );
    }
    out.push_str("];\n");
    let output = PathBuf::from(std::env::var_os("OUT_DIR").expect("Cargo must set OUT_DIR"))
        .join("catalog.rs");
    std::fs::write(output, out).expect("failed to write the generated catalog");
}
